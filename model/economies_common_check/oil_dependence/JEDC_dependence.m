function JEDC_dependence(outdir, panel_csv, shares_xlsx, generic_csv)
%JEDC_DEPENDENCE  Is the oil-volatility effect stronger where oil matters more?
%
%   Run it from the folder it lives in,
%   model/economies_common_check/oil_dependence:
%
%     >> JEDC_dependence
%
%   which is the same as
%
%     >> JEDC_dependence('.', 'panel_full.csv', ...
%            '../../../empirical/spread_data.xlsx', 'generic_vol.csv')
%
%   Everything for this comment lives in this one folder: the two R scripts that
%   build the data, the data they build, the tables below, and the source series
%   under fred/ and external/. The only things read from outside are the paper's
%   own inputs in empirical/.
%
% WHICH COMMENTS THIS ANSWERS
%   R1 Major 1c -- Table 1 clusters by country only, while the oil price change
%     and oil volatility are common across countries within a quarter. Every
%     specification here reports four standard errors: plain OLS, clustered by
%     country, clustered by quarter, and two-way.
%   R1 Major 4, empirical part, and R2 Major 5b -- whether the spread response
%     to oil volatility rises with the country's oil import share.
%
% THE PANEL
%   panel_full.csv is the paper's own panel, regenerated by running the data
%   half of empirical/oil_empirical_quarterly_claude.R: 35 oil importers, 99
%   quarters, 3,465 country-quarters, the dependent variable the change in the
%   log spread, and oil volatility the posterior mean of a stochastic-volatility
%   model fitted with the stochvol package, in percent. The rebuild reproduces
%   the Table 1 oil-price-change coefficients that Referee 2 quotes as 0.14 to
%   0.19: specifications 1 to 4 below give 0.188, 0.184, 0.142 and 0.142.
%
%   Specifications 1 to 4 are the paper's reg1, reg2, reg4 and reg5. The
%   controls are dy_diff, tbill_diff, res_diff, rer_avg_diff and the VIX, all in
%   first differences except the VIX.
%
%   dy_diff is NOT GDP growth, which is what its name suggests. In
%   monthly_domestics.xlsx, dy3 is 100 x CommPubG / GDP -- commercial public and
%   publicly guaranteed external debt as a percent of GDP, ranging from 0 to
%   25.3 -- and the script sets dy_diff = diff(dy3). So the paper's preferred
%   specification already controls for the CHANGE IN DEBT TO GDP, which is worth
%   knowing when comparing against a simulated regression: the model's
%   counterpart has to control for it too, or the two are not the same
%   specification. The sister variables are dy = 100 x EDS_PubG / GDP,
%   dy1 = 100 x EDS_PrNG / GDP and dy2 = 100 x EDS_PrGPub / GDP; all four were
%   identified by matching them against the debt stocks over GDP to 1e-14.
%
% WHAT IT WRITES, into outdir:
%   table1_clustering.csv   the paper's specifications, four standard errors each
%   table2_dependence.csv   the interaction specifications
%   table3_terciles.csv     a separate volatility slope per third of the
%                           dependence distribution, assuming no functional form
%   table4_generic_vol.csv  the oil volatility coefficient with generic price
%                           volatility controlled for (R1 M4, last part)
%   table5_subsamples.csv   the same race by period, because it does not come
%                           out the same way in every one
%   table6_timing.csv       the volatility and price coefficients under each
%                           timing of the price change (R2 M6)
%
% Base MATLAB only, no toolboxes. Everything after the main function is local.

if nargin < 1 || isempty(outdir),      outdir      = '.'; end
if nargin < 2 || isempty(panel_csv),   panel_csv   = 'panel_full.csv'; end
if nargin < 3 || isempty(shares_xlsx), shares_xlsx = '../../../empirical/spread_data.xlsx'; end
if nargin < 4 || isempty(generic_csv), generic_csv = 'generic_vol.csv'; end
if ~exist(outdir, 'dir'), mkdir(outdir); end

P   = read_panel(panel_csv);
dep = read_shares(shares_xlsx, P.country);
P   = merge_generic(P, generic_csv);

fprintf('\n');
fprintf('================================================================\n');
fprintf(' R1 MAJOR 1c   clustering, and\n');
fprintf(' R1 MAJOR 4 / R2 MAJOR 5b   oil dependence and the volatility effect\n');
fprintf('================================================================\n');
fprintf('\npanel: %d country-quarters, %d countries, %d quarters\n', ...
        numel(P.y), numel(unique(P.cid)), numel(unique(P.tid)));
fprintf('  oil dependence, %% of GDP: min %.2f  median %.2f  max %.2f\n', ...
        min(dep), median(dep), max(dep));

% Dependence is time-invariant, so the country effects absorb its level and only
% the interaction is identified. Centring it makes the volatility main effect
% the slope at MEAN dependence rather than at a dependence of zero, which no
% country in the sample has.
depc = dep - mean(unique_by(dep, P.cid));

CTRL  = {'dy_diff','tbill_diff','res_diff','rer_avg_diff','VIX'};
BASE  = {'vol','op_diff'};

S = struct('name', {}, 'fe', {}, 'terms', {}, 'b', {}, 'se', {}, 'n', {}, ...
           'gc', {}, 'gt', {}, 'V2', {});
S = addspec(S, 'paper reg1  no FE, no controls',  false, BASE,            P, depc);
S = addspec(S, 'paper reg2  country FE',          true,  BASE,            P, depc);
S = addspec(S, 'paper reg4  controls, no FE',     false, [BASE CTRL],     P, depc);
S = addspec(S, 'paper reg5  controls and FE',     true,  [BASE CTRL],     P, depc);
S = addspec(S, 'reg5 + vol x dependence',         true,  [BASE CTRL {'vol_x_dep'}], P, depc);
S = addspec(S, 'reg5 + both interactions',        true,  [BASE CTRL {'vol_x_dep','op_x_dep'}], P, depc);

fprintf('\nTABLE 1  what the clustering choice does (R1 Major 1c)\n');
fprintf('  the oil volatility coefficient, four standard errors\n\n');
fprintf('  %-32s%10s%9s%9s%9s%9s%8s\n', 'specification', 'coef', 'ols', ...
        'country', 'quarter', 'twoway', 't(2w)');
for i = 1:4
    k = find(strcmp(S(i).terms, 'vol'), 1);
    fprintf('  %-32s%+10.4f%9.4f%9.4f%9.4f%9.4f%+8.2f\n', S(i).name, ...
            S(i).b(k), S(i).se(k,1), S(i).se(k,2), S(i).se(k,3), ...
            S(i).se(k,4), S(i).b(k)/S(i).se(k,4));
end
fprintf('\n  and the oil price change, for comparison\n');
for i = 1:4
    k = find(strcmp(S(i).terms, 'op_diff'), 1);
    fprintf('  %-32s%+10.4f%9.4f%9.4f%9.4f%9.4f%+8.2f\n', S(i).name, ...
            S(i).b(k), S(i).se(k,1), S(i).se(k,2), S(i).se(k,3), ...
            S(i).se(k,4), S(i).b(k)/S(i).se(k,4));
end

% The controls, best-matched to the comment's wording first. It asks for
% "broader imported-input or producer-price volatility", so an intermediate
% -demand PPI and an industrial-inputs index sit closer to it than a
% finished-goods PPI or a food index; the consumer price index is the weakest of
% the set, because it contains energy and so is partly the oil price itself. All
% seven are reported and none is chosen on its result.
CTRLS = {'ippi_vol',  'intermediate PPI'; ...
         'imat_vol',  'intermediate materials'; ...
         'met_vol',   'metals'; ...
         'nfuel_vol', 'non-fuel commodities'; ...
         'ppi_vol',   'finished-goods PPI'; ...
         'fpi_vol',   'food prices'; ...
         'cpi_vol',   'consumer prices'};
for c = 1:size(CTRLS,1)
    S = addspec(S, ['reg5 + ' CTRLS{c,2}], true, [BASE CTRL CTRLS(c,1)], P, depc);
end
S = addspec(S, 'reg5 + intermediate PPI and metals', true, ...
            [BASE CTRL {'ippi_vol','met_vol'}], P, depc);

fprintf('\nTABLE 2  the dependence interaction (R1 Major 4, R2 Major 5b)\n\n');
for i = 5:numel(S)
    fprintf('  %s  [n = %d, %d countries, %d quarters]\n', S(i).name, ...
            S(i).n, S(i).gc, S(i).gt);
    for k = 1:numel(S(i).terms)
        if ~any(strcmp(S(i).terms{k}, [{'vol','op_diff'}, {'vol_x_dep','op_x_dep'}]))
            continue
        end
        fprintf('    %-14s %+10.4f   ols %7.4f   2w %7.4f   t(2w) %+6.2f\n', ...
                S(i).terms{k}, S(i).b(k), S(i).se(k,1), S(i).se(k,4), ...
                S(i).b(k)/S(i).se(k,4));
    end
    fprintf('\n');
end

% ---- table 4: does oil volatility survive a generic price control? -----
fprintf('TABLE 4  oil volatility against generic price volatility (R1 Major 4)\n');
fprintf('  both volatilities are posterior means from the same stochvol\n');
fprintf('  estimator with an AR(1) design, so they are measured like for like\n\n');
names = [{'paper reg5  controls and FE'}, ...
         cellfun(@(x) ['reg5 + ' x], CTRLS(:,2)', 'UniformOutput', false), ...
         {'reg5 + intermediate PPI and metals'}];
for i = cellfun(@(nm) find(strcmp({S.name}, nm), 1), names)
    fprintf('  %s  [n = %d, %d quarters]\n', S(i).name, S(i).n, S(i).gt);
    for k = 1:numel(S(i).terms)
        if ~any(strcmp(S(i).terms{k}, [{'vol'}, CTRLS(:,1)'])), continue; end
        fprintf('    %-12s %+10.4f   ols %7.4f   2w %7.4f   t(2w) %+6.2f\n', ...
                S(i).terms{k}, S(i).b(k), S(i).se(k,1), S(i).se(k,4), ...
                S(i).b(k)/S(i).se(k,4));
    end
    fprintf('\n');
end

% Correlated regressors: the individual t statistics are not the right test, so
% the joint one is reported beside them. If the pair is jointly significant while
% neither is individually so, the data cannot separate them -- which is a
% different finding from the pair carrying no information.
i4 = find(strcmp({S.name}, 'paper reg5  controls and FE'), 1);
[W1, p1] = wald(S(i4), {'vol'});
fprintf('  oil volatility alone:                         chi2(1) = %5.2f, p = %.4f\n', W1, p1);
for c = 1:size(CTRLS,1)
    ii = find(strcmp({S.name}, ['reg5 + ' CTRLS{c,2}]), 1);
    [W, pj] = wald(S(ii), {'vol', CTRLS{c,1}});
    fprintf('  oil and %-24s jointly:  chi2(2) = %5.2f, p = %.4f\n', ...
            CTRLS{c,2}, W, pj);
end
fprintf('\n');
for c = 1:size(CTRLS,1)
    qv = unique_by([P.vol P.(fieldname(CTRLS{c,1}))], P.tid);
    ok = all(~isnan(qv), 2);
    r  = corrcoef(qv(ok,1), qv(ok,2));
    fprintf('  correlation of oil volatility with %-24s %+.3f over %d quarters\n', ...
            CTRLS{c,2}, r(1,2), sum(ok));
end
fprintf('\n');

% ---- table 6: which price change is on the right-hand side (R2 M6) -----
% The author's script builds op_diff as diff(lag(log_real_price)), so it is the
% price change of the PREVIOUS quarter. R2 Major 6 compares the model's spread
% response with this coefficient, and the comparison only works if the model's
% counterpart uses the same timing. Both are estimated here so the simulated
% regression in ../simulated_regression can be read against the right one.
CTRL_NODEBT = CTRL(~strcmp(CTRL, 'dy_diff'));
TM = {'op_diff',     'lagged price change (as the paper)'; ...
      'op_diff_now', 'contemporaneous price change'};
fprintf('TABLE 6  which price change is on the right-hand side (R2 Major 6)\n\n');
fprintf('  %-52s%11s%8s%12s%8s%12s%8s\n', 'timing and debt control', ...
        'volatility', 't(2w)', 'price', 't(2w)', 'd debt/GDP', 't(2w)');
fh = fopen(fullfile(outdir, 'table6_timing.csv'), 'w');
fpc(fh, ['timing,coef_volatility,se_twoway_volatility,t_twoway_volatility,' ...
         'coef_price,se_twoway_price,t_twoway_price,coef_ddebt_gdp,' ...
         'se_twoway_ddebt_gdp,t_twoway_ddebt_gdp,n,countries,quarters\n']);
for m = 1:size(TM,1)
    for dbt = [true false]
        if dbt, C = CTRL; dtag = 'with debt/GDP'; else, C = CTRL_NODEBT; dtag = 'no debt/GDP'; end
        Sx = addspec(struct('name',{},'fe',{},'terms',{},'b',{},'se',{},'n',{}, ...
                            'gc',{},'gt',{},'V2',{}), ...
                     TM{m,2}, true, [{'vol'} TM(m,1) C], P, depc);
        jv = find(strcmp(Sx.terms,'vol'), 1);
        jp = find(strcmp(Sx.terms, TM{m,1}), 1);
        jd = find(strcmp(Sx.terms,'dy_diff'), 1);
        if isempty(jd), bd = NaN; sd = NaN; else, bd = Sx.b(jd); sd = Sx.se(jd,4); end
        lbl = sprintf('%s, %s', TM{m,2}, dtag);
        fprintf('  %-52s%+11.4f%+8.2f%+12.4f%+8.2f%+12.4f%+8.2f\n', lbl, ...
                Sx.b(jv), Sx.b(jv)/Sx.se(jv,4), Sx.b(jp), Sx.b(jp)/Sx.se(jp,4), ...
                bd, bd/sd);
        fpc(fh, '%s,%.6f,%.6f,%.3f,%.6f,%.6f,%.3f,%.6f,%.6f,%.3f,%d,%d,%d\n', ...
                csvq(lbl), Sx.b(jv), Sx.se(jv,4), Sx.b(jv)/Sx.se(jv,4), ...
                Sx.b(jp), Sx.se(jp,4), Sx.b(jp)/Sx.se(jp,4), ...
                bd, sd, bd/sd, Sx.n, Sx.gc, Sx.gt);
    end
end
fclose(fh);
fprintf('\n  The two have opposite signs on the price, and neither is\n');
fprintf('  distinguishable from zero once the quarter dimension is clustered.\n\n');

% ---- table 5: the race is not stable across periods --------------------
% Both volatility series peak in 2008, so the first question is whether the
% horse race is a crisis artefact. It is not: dropping 2007-2009 leaves it
% standing. But it does not hold in the last six years, and a result that
% reverses between subperiods should be reported as unstable rather than won.
PER = {'full sample',          true(size(P.yr)); ...
       'excluding 2007-2009',  P.yr < 2007 | P.yr > 2009; ...
       'excluding 2008-2009',  P.yr < 2008 | P.yr > 2009; ...
       '1995-2007',            P.yr <= 2007; ...
       '2010 onwards',         P.yr >= 2010};
CT = CTRLS;
RT = {};
fprintf('TABLE 5  the same race, by period, against each control\n\n');
for c = 1:size(CT,1)
    T2 = build(P, [BASE CTRL CT(c,1)], depc);
    jo = find(strcmp(T2.terms, 'vol'), 1);
    jc = find(strcmp(T2.terms, CT{c,1}), 1);
    fprintf('  control: %s\n', CT{c,2});
    fprintf('  %-22s%6s%5s%11s%9s%8s%11s%9s%8s\n', 'sample', 'n', 'q', ...
            'oil', '2w se', 't', 'control', '2w se', 't');
    for r = 1:size(PER,1)
        sel = PER{r,2}(T2.keep);
        [b, se, n, ~, gt] = cluster_ols(T2.y, T2.X, P.cid(T2.keep), ...
                                        P.tid(T2.keep), true, sel);
        fprintf('  %-22s%6d%5d%+11.4f%9.4f%+8.2f%+11.4f%9.4f%+8.2f\n', ...
                PER{r,1}, n, gt, b(jo), se(jo,4), b(jo)/se(jo,4), ...
                b(jc), se(jc,4), b(jc)/se(jc,4));
        RT{end+1} = struct('ctrl', CT{c,2}, 'name', PER{r,1}, 'n', n, ...
                           'gt', gt, 'bo', b(jo), 'so', se(jo,4), ...
                           'bf', b(jc), 'sf', se(jc,4));            %#ok<AGROW>
    end
    fprintf('\n');
end
fprintf('  Both controls tell the same story, which is why it is worth stating:\n');
fprintf('  before 2008 the broad price measure wins and oil carries nothing; from\n');
fprintf('  2010 the ordering reverses. The late window is only about 20 quarters,\n');
fprintf('  so its two-way standard errors rest on 20 time clusters and should not\n');
fprintf('  be read as precisely as the t statistics suggest.\n\n');

% the Table 4 specifications, written out -- announced above and easy to forget
fh = fopen(fullfile(outdir, 'table4_generic_vol.csv'), 'w');
fpc(fh, ['specification,term,coefficient,se_ols,se_country,se_quarter,' ...
         'se_twoway,t_ols,t_twoway,n,countries,quarters\n']);
for i = cellfun(@(nm) find(strcmp({S.name}, nm), 1), names)
    for k = 1:numel(S(i).terms)
        wrow(fh, S(i), k);
    end
end
fclose(fh);

fh = fopen(fullfile(outdir, 'table5_subsamples.csv'), 'w');
fpc(fh, ['control,sample,n,quarters,oil_vol,oil_se_twoway,oil_t,' ...
         'control_coef,control_se_twoway,control_t\n']);
for r = 1:numel(RT)
    q = RT{r};
    fpc(fh, '%s,%s,%d,%d,%.6f,%.6f,%.3f,%.6f,%.6f,%.3f\n', csvq(q.ctrl), ...
            csvq(q.name), q.n, q.gt, q.bo, q.so, q.bo/q.so, q.bf, q.sf, q.bf/q.sf);
end
fclose(fh);

% ---- terciles -----------------------------------------------------------
ud = unique_by(dep, P.cid);
lo = qtile(ud, 1/3); hi = qtile(ud, 2/3);
g  = 1 + (dep > lo) + (dep > hi);
T  = build(P, [BASE CTRL], depc);
X  = T.X;
jv = find(strcmp(T.terms, 'vol'), 1);
X(:, jv) = [];                                 % replace vol with three slopes
tn = T.terms; tn(jv) = [];
X  = [X, (g(T.keep)==1).*P.vol(T.keep), (g(T.keep)==2).*P.vol(T.keep), ...
         (g(T.keep)==3).*P.vol(T.keep)];
tn = [tn, {'vol x low','vol x mid','vol x high'}];
[bt, set_, nt, gct, gtt] = cluster_ols(T.y, X, P.cid(T.keep), P.tid(T.keep), true);

fprintf('TABLE 3  a separate volatility slope per third of the dependence range\n');
fprintf('  country thirds: dependence <= %.2f, <= %.2f, above\n\n', lo, hi);
for k = 1:numel(tn)
    if ~startsWith(tn{k}, 'vol x') && ~strcmp(tn{k}, 'op_diff'), continue; end
    fprintf('    %-14s %+10.4f   ols %7.4f   2w %7.4f   t(2w) %+6.2f\n', ...
            tn{k}, bt(k), set_(k,1), set_(k,4), bt(k)/set_(k,4));
end
ih = find(strcmp(tn,'vol x high'),1); il = find(strcmp(tn,'vol x low'),1);
fprintf('\n    high third minus low third: %+.4f\n', bt(ih) - bt(il));
fprintf('    n = %d, %d countries, %d quarters\n', nt, gct, gtt);

% ---- files ---------------------------------------------------------------
fh = fopen(fullfile(outdir, 'table1_clustering.csv'), 'w');
fpc(fh, ['specification,term,coefficient,se_ols,se_country,se_quarter,' ...
         'se_twoway,t_ols,t_twoway,n,countries,quarters\n']);
for i = 1:4
    for k = 1:numel(S(i).terms)
        wrow(fh, S(i), k);
    end
end
fclose(fh);

fh = fopen(fullfile(outdir, 'table2_dependence.csv'), 'w');
fpc(fh, ['specification,term,coefficient,se_ols,se_country,se_quarter,' ...
         'se_twoway,t_ols,t_twoway,n,countries,quarters\n']);
for i = 5:numel(S)
    for k = 1:numel(S(i).terms)
        wrow(fh, S(i), k);
    end
end
fclose(fh);

fh = fopen(fullfile(outdir, 'table3_terciles.csv'), 'w');
fpc(fh, 'term,coefficient,se_ols,se_country,se_quarter,se_twoway,t_twoway,n\n');
for k = 1:numel(tn)
    fpc(fh, '%s,%.6f,%.6f,%.6f,%.6f,%.6f,%.3f,%d\n', csvq(tn{k}), bt(k), ...
            set_(k,1), set_(k,2), set_(k,3), set_(k,4), bt(k)/set_(k,4), nt);
end
fpc(fh, '%s,%.6f,,,,,,%d\n', csvq('high third minus low third'), ...
        bt(ih)-bt(il), nt);
fclose(fh);

fprintf('\nwritten into %s\n', outdir);
fprintf('  table1_clustering.csv  table2_dependence.csv  table3_terciles.csv\n');
fprintf('  table4_generic_vol.csv table5_subsamples.csv\n\n');
end


function wrow(fh, s, k)
fpc(fh, '%s,%s,%.6f,%.6f,%.6f,%.6f,%.6f,%.3f,%.3f,%d,%d,%d\n', ...
        csvq(s.name), csvq(s.terms{k}), s.b(k), s.se(k,1), s.se(k,2), ...
        s.se(k,3), s.se(k,4), s.b(k)/s.se(k,1), s.b(k)/s.se(k,4), ...
        s.n, s.gc, s.gt);
end


function S = addspec(S, name, fe, terms, P, depc)
T = build(P, terms, depc);
[b, se, n, gc, gt, V2] = cluster_ols(T.y, T.X, P.cid(T.keep), P.tid(T.keep), fe);
S(end+1) = struct('name', name, 'fe', fe, 'terms', {T.terms}, 'b', b, ...
                  'se', se, 'n', n, 'gc', gc, 'gt', gt, 'V2', V2);
end


function [W, p] = wald(s, terms)
%WALD  Joint test that the named coefficients are all zero, two-way clustered.
%
% The point of this is collinearity. When two correlated regressors are entered
% together, neither need be individually significant while the pair carries real
% information, and only the joint test distinguishes that from the pair carrying
% none. On 2 degrees of freedom the chi-squared tail is exp(-W/2) exactly, so no
% toolbox is needed.
j = zeros(numel(terms), 1);
for i = 1:numel(terms)
    j(i) = find(strcmp(s.terms, terms{i}), 1);
end
b = s.b(j);
V = s.V2(j, j);
W = b' * (V \ b);
k = numel(j);
if k == 2
    p = exp(-W/2);
elseif k == 1
    p = erfc(sqrt(W/2));
else
    p = NaN;                       % add a chi2 tail here if a 3+ df test is wanted
end
end


function T = build(P, terms, depc)
%BUILD  Assemble the design matrix and drop rows missing anything it needs.
n = numel(P.y);
X = zeros(n, numel(terms));
for j = 1:numel(terms)
    switch terms{j}
        case 'vol_x_dep', X(:,j) = P.vol .* depc;
        case 'op_x_dep',  X(:,j) = P.op  .* depc;
        otherwise,        X(:,j) = P.(fieldname(terms{j}));
    end
end
keep = ~isnan(P.y) & all(~isnan(X), 2);
T = struct('y', P.y(keep), 'X', X(keep,:), 'keep', keep, 'terms', {terms});
end


function f = fieldname(t)
switch t
    case 'vol',          f = 'vol';
    case 'op_diff',      f = 'op';
    case 'op_diff_now',  f = 'opn';
    case 'dy_diff',      f = 'dy';
    case 'tbill_diff',   f = 'tb';
    case 'res_diff',     f = 'res';
    case 'rer_avg_diff', f = 'rer';
    case 'VIX',          f = 'vix';
    case 'cpi_vol',      f = 'cpiv';
    case 'tbill_vol',    f = 'tbv';
    case 'fpi_vol',      f = 'fpiv';
    case 'ppi_vol',      f = 'ppiv';
    case 'ippi_vol',     f = 'ippiv';
    case 'imat_vol',     f = 'imatv';
    case 'met_vol',      f = 'metv';
    case 'nfuel_vol',    f = 'nfuelv';
    otherwise, error('JEDC_dependence:term', 'unknown term %s', t);
end
end


function [b, se, n, gc, gt, V2] = cluster_ols(y, X, cid, tid, fe, sel)
if nargin >= 6 && ~isempty(sel)
    y = y(sel); X = X(sel,:); cid = cid(sel); tid = tid(sel);
end
%CLUSTER_OLS  OLS with optional country fixed effects and four standard errors.
%
% se has one row per coefficient and four columns: plain OLS, clustered by
% country, clustered by quarter, two-way.
%
% Why the quarter dimension is not optional here: oil volatility and the oil
% price change are GLOBAL series, the same number for every country in a given
% quarter, so the residuals are correlated across the whole cross-section at
% each date. Clustering by country alone leaves that correlation out.
%
% Two-way is Cameron, Gelbach and Miller: country meat plus quarter meat minus
% the intersection. Each component carries G/(G-1) and nothing further; with 35
% and 99 clusters the choice of finite-sample correction moves the third decimal
% place, and saying which one is used matters more than which it is.
[~, ~, ci] = unique(cid);
[~, ~, ti] = unique(tid);
n = numel(y);

if fe
    yd = demean(y, ci);
    Xd = zeros(size(X));
    for j = 1:size(X,2), Xd(:,j) = demean(X(:,j), ci); end
    kabs = numel(unique(ci));
else
    yd = y;
    Xd = [X, ones(n,1)];          % the constant goes last so term order holds
    kabs = 0;
end

XX = Xd' * Xd;
b  = XX \ (Xd' * yd);
e  = yd - Xd * b;
k  = size(Xd,2);

% The sandwich is written as (XX\M)/XX rather than inv(XX)*M*inv(XX): same
% quantity, better conditioned, and it keeps the linter quiet.
s2 = (e' * e) / max(n - k - kabs, 1);
Vo = s2 * (XX \ eye(k));

gc = numel(unique(ci)); gt = numel(unique(ti));
Mc = meat(Xd, e, ci);
Mt = meat(Xd, e, ti);
Mb = meat(Xd, e, (ci-1)*gt + ti);

Vc = (XX \ ((gc/(gc-1)) * Mc)) / XX;
Vt = (XX \ ((gt/(gt-1)) * Mt)) / XX;
V2 = (XX \ ((gc/(gc-1))*Mc + (gt/(gt-1))*Mt - Mb)) / XX;

se = [sqrt(max(diag(Vo),0)), sqrt(max(diag(Vc),0)), ...
      sqrt(max(diag(Vt),0)), sqrt(nanneg(diag(V2)))];
if ~fe
    se = se(1:end-1, :); b = b(1:end-1);           % drop the constant's row
    V2 = V2(1:end-1, 1:end-1);
end
end


function d = nanneg(d)
if any(d < 0)
    warning('JEDC_dependence:psd', ...
            'two-way variance has %d negative diagonal entry/entries; NaN reported', ...
            sum(d < 0));
end
d(d < 0) = NaN;
end


function M = meat(X, e, g)
k = size(X,2);
M = zeros(k);
ug = unique(g);
for i = 1:numel(ug)
    m = (g == ug(i));
    s = X(m,:)' * e(m);
    M = M + s * s';
end
end


function v = demean(v, gi)
s = accumarray(gi, v);
c = accumarray(gi, 1);
v = v - s(gi) ./ c(gi);
end


function u = unique_by(v, gi)
%UNIQUE_BY  One row of v per group, for statistics over groups and not rows.
[g, ia] = unique(gi);                                              %#ok<ASGLU>
u = v(ia, :);
end


