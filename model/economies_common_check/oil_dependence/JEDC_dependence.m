function P = merge_generic(P, path)
%MERGE_GENERIC  Volatility of a non-oil price and of the global interest rate.
%
% Fitted with the same estimator and seed the paper uses for oil -- stochvol
% with an AR(1) design matrix -- so the coefficients can be compared. Written by
% the R helper that regenerates them; if the file is absent the two columns come
% back as NaN and the specifications that need them drop out rather than fail.
VC = {'cpi_vol','cpiv'; 'tbill_vol','tbv'; 'fpi_vol','fpiv'; ...
      'ppi_vol','ppiv'; 'ippi_vol','ippiv'; 'imat_vol','imatv'; ...
      'met_vol','metv'; 'nfuel_vol','nfuelv'};
for v = 1:size(VC,1)
    P.(VC{v,2}) = nan(size(P.y));
end
if ~exist(path, 'file')
    warning('merge_generic:missing', ...
            '%s not found; the generic-volatility specifications will be empty', path);
    return
end
T = readtable(path, 'TreatAsMissing', {'NA'}, 'VariableNamingRule', 'preserve');
qd = string(T.qd);
for i = 1:numel(qd)
    m = (P.qd == qd(i));
    if ~any(m), continue; end
    for v = 1:size(VC,1)
        if any(strcmp(T.Properties.VariableNames, VC{v,1}))
            P.(VC{v,2})(m) = T.(VC{v,1})(i);
        end
    end
end
end


function dep = read_shares(path, country)
%READ_SHARES  The country-level oil import share, merged onto the panel.
%
% The panel uses World Bank country names and the import_gdp sheet uses short
% ones, so three have to be aliased by hand. The El Salvador entry is also
% misspelled in the sheet, without the second L -- the same typo that drops it
% from the elasticity estimates unless it is repaired. All three aliases are
% listed here rather than edited into the spreadsheet, which is left as
% received, and the function fails loudly if any panel country goes unmatched.
ALIAS = {'EL SAVADOR',  'EL SALVADOR'; ...
         'KOREA',       'KOREA, REP.'; ...
         'TRINIDAD',    'TRINIDAD AND TOBAGO'};

C = readcell(path, 'Sheet', 'import_gdp');
names = strings(0); vals = [];
for i = 2:size(C,1)
    nm = upper(strtrim(tostr(C{i,1})));
    if isempty(nm), continue; end
    j = find(strcmp(ALIAS(:,1), nm), 1);
    if ~isempty(j), nm = ALIAS{j,2}; end
    x = tonum(C{i,2});
    if isnan(x), continue; end
    names(end+1,1) = nm;                                           %#ok<AGROW>
    vals(end+1,1)  = x;                                            %#ok<AGROW>
end

dep = nan(numel(country), 1);
for i = 1:numel(country)
    j = find(names == country(i), 1);
    if ~isempty(j), dep(i) = vals(j); end
end
miss = unique(country(isnan(dep)));
if ~isempty(miss)
    error('read_shares:merge', 'no oil import share for: %s', ...
          strjoin(cellstr(miss), ', '));
end
end


function s = tostr(x)
if isnumeric(x) && isscalar(x) && isnan(x), s = ''; return; end
if ischar(x), s = x; return; end
if isstring(x), s = char(x); return; end
if isnumeric(x), s = num2str(x); return; end
s = '';
end


function v = tonum(x)
if isnumeric(x) && isscalar(x), v = double(x); return; end
if ischar(x) || isstring(x), v = str2double(x); return; end
v = NaN;
end


function q = qtile(v, p)
s = sort(v(:));
if numel(s) == 1, q = s(1); return; end
h  = (numel(s)-1)*p;
lo = floor(h);
hi = min(lo+1, numel(s)-1);
q  = s(lo+1) + (h-lo)*(s(hi+1) - s(lo+1));
end


function s = csvq(s)
if any(s == ',') || any(s == '"') || any(s == char(10)) || any(s == char(13))
    s = ['"' strrep(s, '"', '""') '"'];
end
end


